"""Every file that the Open Images V7 download page links to, pinned.

The annotations come from Google Cloud Storage, with the md5 that its `x-goog-hash`
header reports. The images come as the tars that CVDF publishes on S3, with their
ETags. Each file lands at its published name, as clicking every link would leave it.
"""

from cv_lakehouse.sources.published_files import (
    Checksum,
    ChecksumKind,
    PublishedFile,
)

TAR_URL = "https://open-images-dataset.s3.amazonaws.com/tar/{name}"


def _gcs_file(*, url: str, size: int, md5_base64: str) -> PublishedFile:
    return PublishedFile(
        path=url.rsplit("/", maxsplit=1)[-1],
        url=url,
        size=size,
        checksum=Checksum(kind=ChecksumKind.MD5_BASE64, value=md5_base64),
    )


def _s3_tar(*, name: str, size: int, etag: str) -> PublishedFile:
    return PublishedFile(
        path=name,
        url=TAR_URL.format(name=name),
        size=size,
        checksum=Checksum(kind=ChecksumKind.S3_ETAG, value=etag),
    )


